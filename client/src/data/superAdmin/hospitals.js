export function withHospitalDisplay(hospital) {
  const plan = getPlanByName(hospital.plan);
  const totalUsers = Object.values(hospital.users).reduce((sum, count) => sum + count, 0);
  return { ...hospital, adminName: `${hospital.adminFirstName} ${hospital.adminLastName}`, totalUsers, planDetails: plan };
}

export function getHospitals() {
  return hospitals.map(withHospitalDisplay);
}

export function getHospitalById(hospitalId) {
  const hospital = hospitals.find((item) => item.id === hospitalId);
  return hospital ? withHospitalDisplay(hospital) : null;
}
